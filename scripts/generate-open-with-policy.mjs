import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '..');
const check = process.argv.includes('--check');

const policyPath = path.join(repoRoot, 'ipc/schema/v1/open-with-policy.json');
const policy = JSON.parse(fs.readFileSync(policyPath, 'utf8'));

function fail(message) {
  console.error(`Open With policy generation failed: ${message}`);
  process.exit(1);
}

function normalizeList(name, { prefix = '' } = {}) {
  const values = policy[name];
  if (!Array.isArray(values) || values.length === 0) {
    fail(`${name} must be a non-empty array.`);
  }

  const seen = new Set();
  return values.map((value) => {
    if (typeof value !== 'string') {
      fail(`${name} entries must be strings.`);
    }

    const normalized = value.trim().replace(/^\./u, '').toLowerCase();
    if (!/^[a-z0-9_-]+$/u.test(normalized)) {
      fail(`${name} entry "${value}" has an unsupported character.`);
    }

    if (seen.has(normalized)) {
      fail(`${name} contains duplicate entry "${normalized}".`);
    }

    seen.add(normalized);
    return `${prefix}${normalized}`;
  });
}

const deniedExecutableNames = normalizeList('deniedExecutableNames');
const deniedTargetExtensions = normalizeList('deniedTargetExtensions');
const csharpDeniedTargetExtensions = normalizeList('deniedTargetExtensions', { prefix: '.' });

function csharpArray(name, values) {
  return [
    `    public static readonly string[] ${name} =`,
    '    [',
    ...values.map((value) => `        ${JSON.stringify(value)},`),
    '    ];',
  ].join('\n');
}

function rustArray(name, values) {
  return [
    '#[rustfmt::skip]',
    `pub(crate) const ${name}: &[&str] = &[`,
    ...values.map((value) => `    ${JSON.stringify(value)},`),
    '];',
  ].join('\n');
}

const csharpContent = `// <auto-generated />
// Generated by scripts/generate-open-with-policy.mjs from ipc/schema/v1/open-with-policy.json.

namespace SimpleFile.Core;

internal static class OpenWithPolicyGenerated
{
${csharpArray('DeniedTargetExtensions', csharpDeniedTargetExtensions)}
}
`;

const rustContent = `// @generated
// Generated by scripts/generate-open-with-policy.mjs from ipc/schema/v1/open-with-policy.json.

${rustArray('DENIED_EXECUTABLE_NAMES', deniedExecutableNames)}

${rustArray('DENIED_TARGET_EXTENSIONS', deniedTargetExtensions)}
`;

function writeOrCheck(relativePath, content) {
  const absolutePath = path.join(repoRoot, relativePath);
  if (check) {
    const current = fs.existsSync(absolutePath) ? fs.readFileSync(absolutePath, 'utf8') : '';
    if (current !== content) {
      console.error(`${relativePath} is out of date. Run npm run generate:open-with-policy.`);
      process.exitCode = 1;
    }
    return;
  }

  fs.mkdirSync(path.dirname(absolutePath), { recursive: true });
  fs.writeFileSync(absolutePath, content);
}

writeOrCheck('src-winui/SimpleFile.Core/OpenWithPolicy.Generated.cs', csharpContent);
writeOrCheck('crates/simplefile-core/src/open_with_policy_generated.rs', rustContent);

if (!process.exitCode) {
  console.log(check ? 'Open With policy generated files are current.' : 'Open With policy generated files updated.');
}
