import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '..');
const check = process.argv.includes('--check');

const schemaPath = path.join(repoRoot, 'ipc/schema/v1/media-formats.json');
const schema = JSON.parse(fs.readFileSync(schemaPath, 'utf8'));

function fail(message) {
  console.error(`Media format generation failed: ${message}`);
  process.exit(1);
}

if (!Array.isArray(schema.formats) || schema.formats.length === 0) {
  fail('formats must be a non-empty array.');
}

const seen = new Set();
for (const format of schema.formats) {
  if (typeof format.name !== 'string' || format.name.trim() === '') {
    fail('every format needs a name.');
  }
  if (!Array.isArray(format.extensions) || format.extensions.length === 0) {
    fail(`${format.name} needs at least one extension.`);
  }
  for (const extension of format.extensions) {
    if (typeof extension !== 'string' || !/^[a-z0-9]+$/u.test(extension)) {
      fail(`${format.name} extension "${extension}" must be lowercase letters and digits, without a dot.`);
    }
    if (seen.has(extension)) {
      fail(`extension "${extension}" is listed twice.`);
    }
    seen.add(extension);
  }
}

// The video extensions the video process makes thumbnails of. None may also be a picture format: an extension goes
// to one program.
if (!Array.isArray(schema.video) || schema.video.length === 0) {
  fail('video must be a non-empty array.');
}
const seenVideo = new Set();
for (const extension of schema.video) {
  if (typeof extension !== 'string' || !/^[a-z0-9]+$/u.test(extension)) {
    fail(`video extension "${extension}" must be lowercase letters and digits, without a dot.`);
  }
  if (seenVideo.has(extension)) {
    fail(`video extension "${extension}" is listed twice.`);
  }
  if (seen.has(extension)) {
    fail(`extension "${extension}" is listed as a picture format and as a video.`);
  }
  seenVideo.add(extension);
}

// Code-point order, which is what Rust's sort and C#'s ordinal comparer give.
const inOrder = (values) => [...values].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
const extensions = inOrder(seen);
const videoExtensions = inOrder(seenVideo);
const source = 'scripts/generate-media-formats.mjs from ipc/schema/v1/media-formats.json';

const csharpContent = `// <auto-generated />
// Generated by ${source}.

#nullable enable

namespace SimpleFile.Core;

/// <summary>
/// The image formats SumaFile's media process decodes for thumbnails and previews, and the video extensions its
/// video process makes thumbnails of.
/// </summary>
public static class MediaFormats
{
    private static readonly string[] SortedExtensions =
    [
${extensions.map((value) => `        ${JSON.stringify(value)},`).join('\n')}
    ];

    private static readonly HashSet<string> ExtensionSet = new(SortedExtensions, StringComparer.OrdinalIgnoreCase);

    /// <summary>The extensions, lowercase, without a dot, in ordinal order.</summary>
    public static IReadOnlyList<string> Extensions => SortedExtensions;

    /// <summary>True for an extension (with or without its dot), a file name or a path of one of these formats.</summary>
    public static bool IsMediaProcessFormat(string? pathOrExtension) =>
        ExtensionCatalog.Contains(ExtensionSet, pathOrExtension);

    private static readonly string[] SortedVideoExtensions =
    [
${videoExtensions.map((value) => `        ${JSON.stringify(value)},`).join('\n')}
    ];

    private static readonly HashSet<string> VideoExtensionSet = new(SortedVideoExtensions, StringComparer.OrdinalIgnoreCase);

    /// <summary>The video extensions, lowercase, without a dot, in ordinal order.</summary>
    public static IReadOnlyList<string> VideoExtensions => SortedVideoExtensions;

    /// <summary>True for an extension (with or without its dot), a file name or a path of a video.</summary>
    public static bool IsVideoFormat(string? pathOrExtension) =>
        ExtensionCatalog.Contains(VideoExtensionSet, pathOrExtension);
}
`;

const rustContent = `// @generated
// Generated by ${source}.

/// The extensions the media process decodes: lowercase, without a dot, sorted.
#[rustfmt::skip]
pub const MEDIA_PROCESS_EXTENSIONS: &[&str] = &[
${extensions.map((value) => `    ${JSON.stringify(value)},`).join('\n')}
];

/// The video extensions the video process makes thumbnails of: lowercase,
/// without a dot, sorted.
#[rustfmt::skip]
pub const VIDEO_EXTENSIONS: &[&str] = &[
${videoExtensions.map((value) => `    ${JSON.stringify(value)},`).join('\n')}
];
`;

function writeOrCheck(relativePath, content) {
  const absolutePath = path.join(repoRoot, relativePath);
  const normalized = `${content.replace(/\r\n/g, '\n').replace(/\s+$/u, '')}\n`;
  if (check) {
    const current = fs.existsSync(absolutePath)
      ? fs.readFileSync(absolutePath, 'utf8').replace(/\r\n/g, '\n')
      : '';
    if (current !== normalized) {
      console.error(`${relativePath} is out of date. Run npm run generate:media-formats.`);
      process.exitCode = 1;
    }
    return;
  }

  fs.mkdirSync(path.dirname(absolutePath), { recursive: true });
  fs.writeFileSync(absolutePath, normalized);
}

writeOrCheck('src-winui/SimpleFile.Core/MediaFormats.Generated.cs', csharpContent);
writeOrCheck('crates/sumafile-imaging/src/formats_generated.rs', rustContent);

if (!process.exitCode) {
  console.log(check ? 'Media format generated files are current.' : 'Media format generated files updated.');
}
